//   OIML R22 (relation masse volumique / titre alcoométrique du mélange éthanol-eau).
// - Vins, cidres, bières : masses volumiques usuelles mesurées en œnologie/brasserie
//   (vin ~0.99 kg/L, bière ~1.01 kg/L, cf. littérature technique INRAE/IFBM).
// - Jus, nectars, sodas, boissons lactées et végétales : masses volumiques usuelles
//   des boissons rafraîchissantes sans alcool (BRSA), corrélées à la teneur en sucres
//   dissous (~1.00 kg/L pour une boisson non sucrée proche de l'eau, jusqu'à
//   ~1.04-1.06 kg/L pour un jus pur ou un soda sucré), cohérentes avec les données
//   de composition CIQUAL/INFOODS.
// - Eaux et boissons infusées non sucrées : assimilées à l'eau (~0.998-0.999 kg/L).
//
